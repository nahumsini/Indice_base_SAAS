test('all document content is escaped and active image schemes are rejected', () => {
  const fixture = quotationFixture();
  fixture.title = '<img src=x onerror=alert(1)>';
  fixture.metadata[0].value = '</dd><script>attack()</script>';
  fixture.logoUrl = 'javascript:alert(1)';
  const html = render.buildStandardDocumentHtml(fixture);
  assert.doesNotMatch(html, /<script>|onerror=alert\(1\)>|src="javascript:/);
  assert.match(html, /&lt;script&gt;/);
  assert.equal(render.safeDocumentImageUrl('data:text/html;base64,WA=='), '');
  assert.equal(render.safeDocumentImageUrl('data:image/svg+xml,<svg onload="attack()"/>'), '');
  assert.equal(render.safeDocumentImageUrl('data:image/png;base64,WA=='), 'data:image/png;base64,WA==');
});

