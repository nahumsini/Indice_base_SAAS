test('print engine rejects blank documents and reports blocked popups without leaking the blob', () => {
  const failures = [], revoked = [], blobs = [];
  const engine = printModules({ './documentPrintFeedback': { notifyDocumentPrintFailure: (...args) => failures.push(args) } })('shared/print/documentHtmlPrintEngine.ts');
  const originalWindow = globalThis.window;
  const create = URL.createObjectURL, revoke = URL.revokeObjectURL;
  try {
    globalThis.window = { open: () => null };
    URL.createObjectURL = blob => { blobs.push(blob); return 'blob:fixture'; };
    URL.revokeObjectURL = url => revoked.push(url);
    assert.equal(engine.printDocumentHtml({ bodyHtml: ' ', documentTitle: 'Empty', locale: 'es-MX' }), false);
    assert.equal(blobs.length, 0);
    assert.equal(engine.printDocumentHtml({ bodyHtml: '<p>Contenido</p>', documentTitle: 'Report', locale: 'es-MX' }), false);
    assert.deepEqual(failures, [['es-MX', 'popup-blocked']]);
    assert.deepEqual(revoked, ['blob:fixture']);
    assert.equal(blobs[0].type, 'text/html;charset=utf-8');
  } finally { globalThis.window = originalWindow; URL.createObjectURL = create; URL.revokeObjectURL = revoke; }
});

test('reserved windows print once after font readiness, with thermal paper preserved', async () => {
  const engine = load('shared/print/documentHtmlPrintEngine.ts');
  const originalWindow = globalThis.window;
  const create = URL.createObjectURL, revoke = URL.revokeObjectURL;
  let listener, resolveFonts, count = 0, blob;
  const target = { closed: false, location: { href: 'about:blank', replace(url) { this.href = url; } }, document: { readyState: 'complete', images: [], fonts: { ready: new Promise(resolve => { resolveFonts = resolve; }) } }, addEventListener: (_, callback) => { listener = callback; }, focus() {}, print() { count++; } };
  try {
    globalThis.window = { open: () => { throw new Error('must reuse reserved window'); }, setInterval: () => 1, clearInterval() {}, setTimeout: () => 2 };
    URL.createObjectURL = value => { blob = value; return 'blob:thermal-fixture'; };
    URL.revokeObjectURL = () => {};
    assert.equal(engine.printDocumentHtml({ bodyHtml: '<p>Ticket</p>', documentTitle: 'Ticket', locale: 'es-MX', pageSize: '80mm', targetWindow: target }), true);
    const printing = listener();
    assert.equal(count, 0);
    resolveFonts(); await printing; await listener();
    assert.equal(count, 1);
    assert.match(await blob.text(), /size: 80mm auto/);
    assert.doesNotMatch(await blob.text(), /grid-template-columns: 1fr 1.4fr 1fr/);
  } finally { globalThis.window = originalWindow; URL.createObjectURL = create; URL.revokeObjectURL = revoke; }
});

