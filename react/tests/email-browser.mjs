import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const { chromium } = await import(process.env.INDICE_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true});
try {
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:5198');
 await page.getByRole('button',{name:/Equipo de compras/}).click();
 await page.getByRole('button',{name:'Archivar',exact:true}).click();
 await page.getByRole('button',{name:/Archivados/}).click();
 await page.getByRole('button',{name:/Equipo de compras/}).click();
 await page.getByRole('button',{name:'Mover a entrada'}).click();
 await page.getByRole('button',{name:'Redactar',exact:true}).click();
 await page.getByLabel('Para',{exact:true}).fill('test@example.com');
 await page.getByLabel('Asunto',{exact:true}).fill('Borrador de prueba');
 await page.getByLabel('Mensaje',{exact:true}).fill('Texto de prueba');
 await page.getByRole('button',{name:'Guardar borrador'}).click();
 await page.getByRole('button',{name:/Borradores/}).click();
 await page.getByRole('button',{name:/Borrador de prueba/}).click();
 await page.getByRole('button',{name:'Volver',exact:true}).click();
 await page.getByLabel('Buscar correo').fill('no existe');
 await page.getByText('No hay resultados para esta búsqueda.').waitFor();
 await page.getByLabel('Buscar correo').fill('');
 await page.getByRole('button',{name:/Bandeja de entrada/}).click();
 await page.getByRole('button',{name:/Equipo de compras/}).click();
 mkdirSync('../artifacts/email',{recursive:true});
 await page.screenshot({path:'../artifacts/email/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Volver',exact:true}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'mobile overflow');
 await page.screenshot({path:'../artifacts/email/mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Administrar cuentas'}).click();
 await page.getByRole('button',{name:'Ver conexión'}).first().click();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button',{name:'Entendido'}).click();
 assert.deepEqual(errors,[]);
 console.log('PASS: lectura, archivo/restauración, borrador, búsqueda, móvil; sin errores de React.');
} finally { await browser.close(); }
