import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const { chromium } = await import(process.env.INDICE_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true});
try {
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:5198');
 await page.getByRole('button',{name:/Equipo de compras/}).click();
 await page.getByRole('button',{name:'Acciones',exact:true}).click();
 await page.getByRole('menuitem',{name:'Archive',exact:true}).click();
 await page.getByRole('tab',{name:'Archive',exact:true}).click();
 await page.getByRole('button',{name:/Equipo de compras/}).click();
 await page.getByRole('button',{name:'Acciones',exact:true}).click();
 await page.getByRole('menuitem',{name:'Move to inbox'}).click();
 await page.getByRole('button',{name:'Compose',exact:true}).click();
 await page.getByLabel('To',{exact:true}).fill('test@example.com');
 await page.getByLabel('Subject',{exact:true}).fill('Borrador de prueba');
 await page.getByLabel('Message',{exact:true}).fill('Texto de prueba');
 await page.getByRole('button',{name:'Save draft'}).click();
 await page.getByRole('tab',{name:'Drafts',exact:true}).click();
 await page.getByRole('button',{name:/Borrador de prueba/}).click();
 await page.getByRole('button',{name:'Back',exact:true}).click();
 await page.getByLabel('Search mail').fill('no existe');
 await page.getByText('No messages match your search.').waitFor();
 await page.getByLabel('Search mail').fill('');
 await page.getByRole('tab',{name:'Inbox',exact:true}).click();
 await page.getByRole('button',{name:/Equipo de compras/}).click();
 mkdirSync('../artifacts/email',{recursive:true});
 await page.screenshot({path:'../artifacts/email/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Back',exact:true}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'mobile overflow');
 await page.screenshot({path:'../artifacts/email/mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Compose',exact:true}).click();
 await page.getByLabel('Subject',{exact:true}).fill('Cambios sin guardar');
 await page.getByRole('button',{name:'Cancel',exact:true}).first().click();
 await page.getByRole('heading',{name:'Discard unsaved changes?'}).waitFor();
 assert.equal(await page.getByRole('dialog').count(),1,'confirmation replaces composer');
 await page.getByRole('button',{name:'Keep editing'}).click();
 assert.equal(await page.getByLabel('Subject',{exact:true}).inputValue(),'Cambios sin guardar');
 await page.getByRole('button',{name:'Cancel',exact:true}).first().click();
 await page.getByRole('button',{name:'Discard changes',exact:true}).click();
 await page.getByRole('button',{name:'Connected accounts',exact:true}).first().click();
 await page.getByRole('heading',{name:'Unable to load accounts.'}).waitFor();
 assert.deepEqual(errors,[]);
 console.log('PASS: lectura, archivo/restauración, borrador, búsqueda, móvil; sin errores de React.');
} finally { await browser.close(); }
