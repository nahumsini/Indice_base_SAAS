export function getLearningPracticeCopy(locale: string, id: LearningPracticeId, characterId?: LearningCharacterId | null) {
  const language = locale.split('-')[0] as keyof typeof practiceCopies;
  const copy = practiceCopies[language] ?? practiceCopies.en;
  const values = getPracticeCaseValues(locale, characterId);
  const template = copy[id];
  const resolved = Object.fromEntries(Object.entries(template).map(([key, value]) => [
    key, value.replace(/\{(\w+)\}/g, (_, token: string) => values[token as keyof typeof values]),
  ])) as { [Key in keyof typeof template]: string };
  return { ...resolved, labels: copy.labels };
}

