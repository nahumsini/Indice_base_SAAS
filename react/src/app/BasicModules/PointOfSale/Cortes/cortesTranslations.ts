type Widen<T> =
  T extends (...args: infer Args) => infer Return
    ? (...args: Args) => Return
    : T extends string
      ? string
      : T extends number
        ? number
        : T extends boolean
          ? boolean
          : T extends readonly (infer Item)[]
            ? ReadonlyArray<Widen<Item>>
            : T extends object
              ? { readonly [Key in keyof T]: Widen<T[Key]> }
              : T;

export type CortesCopy = Widen<typeof enCACortes>;

