type KioskCatalogSource = 'es-MX' | 'en-CA';

/** Every supported app locale is explicitly routed to a reviewed kiosk catalog. */
export const pointOfSaleKioskLocaleFallbacks: Record<PointOfSaleLocale, KioskCatalogSource> = {
  'es-MX': 'es-MX',
  'es-CO': 'es-MX',
  'en-US': 'en-CA',
  'en-CA': 'en-CA',
  'fr-CA': 'en-CA',
  'pt-BR': 'en-CA',
  'ko-CA': 'en-CA',
  'zh-CA': 'en-CA',
};

const catalogs: Record<KioskCatalogSource, PointOfSaleKioskTranslations> = {
  'es-MX': esMX,
  'en-CA': enCA,
};

function resolveLocale(locale?: string | null): PointOfSaleLocale {
  return locale && Object.prototype.hasOwnProperty.call(pointOfSaleKioskLocaleFallbacks, locale)
    ? locale as PointOfSaleLocale
    : 'en-CA';
}

export function getPointOfSaleKioskTranslations(locale?: string | null) {
  const resolvedLocale = resolveLocale(locale);
  return {
    copy: catalogs[pointOfSaleKioskLocaleFallbacks[resolvedLocale]],
    locale: resolvedLocale,
  };
}

export function usePointOfSaleKioskTranslations() {
  const { currentLanguage } = useLanguage();
  return useMemo(
    () => getPointOfSaleKioskTranslations(currentLanguage.code),
    [currentLanguage.code],
  );
}
