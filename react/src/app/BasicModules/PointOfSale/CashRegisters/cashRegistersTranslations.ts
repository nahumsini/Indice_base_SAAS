const copyByLocale: Record<PointOfSaleLocale, CashRegistersCopy> = {
  'en-CA': enCACashRegisters,
  'en-US': enCACashRegisters,
  'es-MX': esMXCashRegisters,
  'es-CO': esMXCashRegisters,
  'fr-CA': enCACashRegisters,
  'pt-BR': enCACashRegisters,
  'ko-CA': enCACashRegisters,
  'zh-CA': enCACashRegisters,
};

export function useCashRegistersCopy() {
  const { currentLanguage } = useLanguage();
  const locale = useMemo(() => resolvePointOfSaleLocale(currentLanguage.code), [currentLanguage.code]);
  const copy = useMemo(() => copyByLocale[locale], [locale]);
  return { copy, locale };
}
