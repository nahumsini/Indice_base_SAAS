type SupplierPortalCatalogSource = 'es-MX' | 'en-CA';

/** Every supported application locale is explicitly routed to a reviewed Supplier Portal catalog. */
export const supplierPortalLocaleFallbacks: Record<PointOfSaleLocale, SupplierPortalCatalogSource> = {
  'es-MX': 'es-MX',
  'es-CO': 'es-MX',
  'en-US': 'en-CA',
  'en-CA': 'en-CA',
  'fr-CA': 'en-CA',
  'pt-BR': 'en-CA',
  'ko-CA': 'en-CA',
  'zh-CA': 'en-CA',
};

const catalogs: Record<SupplierPortalCatalogSource, SupplierPortalTranslations> = {
  'es-MX': esMX,
  'en-CA': enCA,
};

function resolveLocale(locale?: string | null): PointOfSaleLocale {
  return locale && Object.prototype.hasOwnProperty.call(supplierPortalLocaleFallbacks, locale)
    ? locale as PointOfSaleLocale
    : 'en-CA';
}

export function getSupplierPortalTranslations(locale?: string | null) {
  const resolvedLocale = resolveLocale(locale);
  return {
    copy: catalogs[supplierPortalLocaleFallbacks[resolvedLocale]],
    locale: resolvedLocale,
  };
}

export function useSupplierPortalTranslations() {
  const { currentLanguage } = useLanguage();
  return useMemo(
    () => getSupplierPortalTranslations(currentLanguage.code),
    [currentLanguage.code],
  );
}
