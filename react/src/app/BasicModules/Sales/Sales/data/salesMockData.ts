import type { SaleLine, SaleRecord } from '../types/salesTypes';

function createMockSaleLine({
  id,
  productId,
  sku,
  productName,
  quantity = 1,
  unitPrice,
  unitCost,
  businessUnitId,
  businessId,
  warehouseId,
  inventoryMovementDraftId,
}: {
  id: string;
  productId: string;
  sku: string;
  productName: string;
  quantity?: number;
  unitPrice: number;
  unitCost: number;
  businessUnitId: string;
  businessId: string;
  warehouseId: string;
  inventoryMovementDraftId?: string;
}): SaleLine {
  const subtotal = quantity * unitPrice;

  return {
    id,
    productId,
    sku,
    productName,
    quantity,
    unitPrice,
    unitCost,
    discountPercent: 0,
    taxPercent: 0,
    subtotal,
    marginAmount: subtotal - (quantity * unitCost),
    businessUnitId,
    businessId,
    warehouseId,
    inventoryMovementDraftId,
    availabilityStatus: 'pending_validation',
  };
}

