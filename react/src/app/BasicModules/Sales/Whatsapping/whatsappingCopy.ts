export function labelFor(code: string, locale: string) {
  const i = locale.startsWith("es")
    ? 1
    : locale.startsWith("fr")
      ? 2
      : locale.startsWith("pt")
        ? 3
        : locale.startsWith("ko")
          ? 4
          : locale.startsWith("zh")
            ? 5
            : 0;
  return states[code]?.[i] ?? code;
}
export function useWhatsappingCopy() {
  const { currentLanguage } = useLanguage();
  const locale = currentLanguage.code;
  return {
    copy: copyFor(locale),
    locale,
    label: (code: string) => labelFor(code, locale),
  };
}
