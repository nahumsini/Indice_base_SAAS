-- Private, user-owned mailbox data derives ownership from its account.
CREATE TABLE email_mailboxes (
    company_id BIGINT NOT NULL,
    account_id CHAR(36) NOT NULL,
    lease_token CHAR(36) NULL,
    lease_until TIMESTAMP(6) NULL,
    last_sync_at TIMESTAMP(6) NULL,
    last_attempt_at TIMESTAMP(6) NULL,
    last_error VARCHAR(64) NULL,
    PRIMARY KEY (company_id, account_id),
    CONSTRAINT fk_email_mailbox_account FOREIGN KEY (company_id,account_id) REFERENCES email_accounts(company_id,id)
);
CREATE TABLE email_folders (
    company_id BIGINT NOT NULL,
    account_id CHAR(36) NOT NULL,
    id CHAR(36) NOT NULL,
    account_version BIGINT NOT NULL,
    remote_name VARCHAR(512) NOT NULL COLLATE utf8mb4_bin,
    kind VARCHAR(16) NOT NULL,
    uid_validity BIGINT NOT NULL DEFAULT 0,
    newest_uid BIGINT NOT NULL DEFAULT 0,
    oldest_uid BIGINT NOT NULL DEFAULT 0,
    has_older BOOLEAN NOT NULL DEFAULT TRUE,
    synced_at TIMESTAMP(6) NULL,
    PRIMARY KEY (company_id,account_id,id),
    UNIQUE KEY uq_email_folder_remote (company_id,account_id,account_version,remote_name),
    CONSTRAINT fk_email_folder_account FOREIGN KEY (company_id,account_id) REFERENCES email_accounts(company_id,id)
);
CREATE TABLE email_messages (
    company_id BIGINT NOT NULL,
    account_id CHAR(36) NOT NULL,
    id CHAR(36) NOT NULL,
    account_version BIGINT NOT NULL,
    folder_id CHAR(36) NULL,
    remote_uid BIGINT NULL,
    uid_validity BIGINT NULL,
    remote_present BOOLEAN NOT NULL DEFAULT TRUE,
    state VARCHAR(16) NOT NULL,
    subject VARCHAR(500) NOT NULL DEFAULT '',
    from_address VARCHAR(320) NOT NULL DEFAULT '',
    from_name VARCHAR(200) NOT NULL DEFAULT '',
    to_json TEXT NOT NULL,
    cc_json TEXT NOT NULL,
    bcc_json TEXT NOT NULL,
    reply_to_json TEXT NOT NULL,
    body_text MEDIUMTEXT NULL,
    body_truncated BOOLEAN NOT NULL DEFAULT FALSE,
    has_attachments BOOLEAN NOT NULL DEFAULT FALSE,
    message_id VARCHAR(512) NULL,
    in_reply_to VARCHAR(512) NULL,
    references_header TEXT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    is_starred BOOLEAN NOT NULL DEFAULT FALSE,
    occurred_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 1,
    send_started_at TIMESTAMP(6) NULL,
    failure_code VARCHAR(64) NULL,
    PRIMARY KEY (company_id,account_id,id),
    UNIQUE KEY uq_email_remote_message (company_id,account_id,folder_id,uid_validity,remote_uid),
    KEY ix_email_message_list (company_id,account_id,state,occurred_at),
    CONSTRAINT fk_email_message_account FOREIGN KEY (company_id,account_id) REFERENCES email_accounts(company_id,id),
    CONSTRAINT fk_email_message_folder FOREIGN KEY (company_id,account_id,folder_id) REFERENCES email_folders(company_id,account_id,id),
    CONSTRAINT ck_email_message_state CHECK (state IN ('RECEIVED','DRAFT','SUBMITTING','ACCEPTED','FAILED','UNKNOWN','DISCARDED'))
);
CREATE TABLE email_send_attempts (
    company_id BIGINT NOT NULL,
    account_id CHAR(36) NOT NULL,
    message_id CHAR(36) NOT NULL,
    id CHAR(36) NOT NULL,
    actor_user_id BIGINT NOT NULL,
    outcome VARCHAR(16) NOT NULL,
    started_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    completed_at TIMESTAMP(6) NULL,
    PRIMARY KEY (company_id,account_id,id),
    UNIQUE KEY uq_email_individual_send (company_id,account_id,message_id),
    KEY ix_email_send_limit (company_id,account_id,started_at),
    CONSTRAINT fk_email_send_message FOREIGN KEY (company_id,account_id,message_id) REFERENCES email_messages(company_id,account_id,id)
);
