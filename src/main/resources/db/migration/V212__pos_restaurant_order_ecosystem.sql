CREATE TABLE pos_restaurant_ecosystems (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT NOT NULL,
    unit_id BIGINT NOT NULL,
    business_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    settlement_cash_register_id BIGINT NOT NULL,
    code VARCHAR(80) NOT NULL,
    name VARCHAR(180) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    currency_code VARCHAR(3) NOT NULL DEFAULT 'MXN',
    created_by_user_id BIGINT NOT NULL,
    updated_by_user_id BIGINT NULL,
    version BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL,
    UNIQUE KEY uk_pos_restaurant_ecosystem_code (company_id, code),
    KEY idx_pos_restaurant_ecosystem_scope (company_id, unit_id, business_id, status),
    KEY idx_pos_restaurant_ecosystem_register (company_id, settlement_cash_register_id),
    CONSTRAINT fk_pos_restaurant_ecosystem_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_pos_restaurant_ecosystem_unit FOREIGN KEY (unit_id) REFERENCES units(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_ecosystem_business FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_ecosystem_warehouse FOREIGN KEY (warehouse_id) REFERENCES sales_inventory_warehouses(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_ecosystem_register FOREIGN KEY (settlement_cash_register_id) REFERENCES pos_cash_registers(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_ecosystem_created_by FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_ecosystem_updated_by FOREIGN KEY (updated_by_user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_pos_restaurant_ecosystem_status CHECK (status IN ('ACTIVE', 'DISABLED', 'REVOKED'))
);

CREATE TABLE pos_restaurant_areas (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT NOT NULL,
    ecosystem_id BIGINT NOT NULL,
    code VARCHAR(80) NOT NULL,
    name VARCHAR(160) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_pos_restaurant_area_code (company_id, ecosystem_id, code),
    KEY idx_pos_restaurant_area_ecosystem (company_id, ecosystem_id, status, sort_order),
    CONSTRAINT fk_pos_restaurant_area_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_pos_restaurant_area_ecosystem FOREIGN KEY (ecosystem_id) REFERENCES pos_restaurant_ecosystems(id) ON DELETE RESTRICT,
    CONSTRAINT chk_pos_restaurant_area_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE pos_restaurant_tables (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT NOT NULL,
    ecosystem_id BIGINT NOT NULL,
    area_id BIGINT NOT NULL,
    code VARCHAR(80) NOT NULL,
    name VARCHAR(160) NOT NULL,
    capacity INT NOT NULL DEFAULT 4,
    operational_status VARCHAR(24) NOT NULL DEFAULT 'AVAILABLE',
    sort_order INT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_pos_restaurant_table_code (company_id, ecosystem_id, code),
    KEY idx_pos_restaurant_table_area (company_id, ecosystem_id, area_id, operational_status),
    CONSTRAINT fk_pos_restaurant_table_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_pos_restaurant_table_ecosystem FOREIGN KEY (ecosystem_id) REFERENCES pos_restaurant_ecosystems(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_table_area FOREIGN KEY (area_id) REFERENCES pos_restaurant_areas(id) ON DELETE RESTRICT,
    CONSTRAINT chk_pos_restaurant_table_capacity CHECK (capacity BETWEEN 1 AND 100),
    CONSTRAINT chk_pos_restaurant_table_status CHECK (operational_status IN ('AVAILABLE', 'OCCUPIED', 'CHECK_REQUESTED', 'CHECKOUT', 'CLEANING', 'BLOCKED'))
);

