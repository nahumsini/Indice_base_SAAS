CREATE TABLE pos_restaurant_orders (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT NOT NULL,
    ecosystem_id BIGINT NOT NULL,
    table_id BIGINT NOT NULL,
    opened_by_user_company_id BIGINT NOT NULL,
    responsible_user_company_id BIGINT NOT NULL,
    source_kiosk_id BIGINT NOT NULL,
    settlement_cash_register_id BIGINT NOT NULL,
    ticket_id BIGINT NULL,
    order_number VARCHAR(80) NOT NULL,
    guest_count INT NOT NULL DEFAULT 1,
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
    currency_code VARCHAR(3) NOT NULL,
    subtotal_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    total_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    claimed_by_user_id BIGINT NULL,
    claimed_at TIMESTAMP NULL,
    check_requested_at TIMESTAMP NULL,
    paid_at TIMESTAMP NULL,
    closed_at TIMESTAMP NULL,
    notes VARCHAR(1000) NULL,
    version BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_pos_restaurant_order_number (company_id, order_number),
    KEY idx_pos_restaurant_order_table (company_id, ecosystem_id, table_id, status),
    KEY idx_pos_restaurant_order_checkout (company_id, settlement_cash_register_id, status, check_requested_at),
    CONSTRAINT fk_pos_restaurant_order_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_pos_restaurant_order_ecosystem FOREIGN KEY (ecosystem_id) REFERENCES pos_restaurant_ecosystems(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_order_table FOREIGN KEY (table_id) REFERENCES pos_restaurant_tables(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_order_opened_by FOREIGN KEY (opened_by_user_company_id) REFERENCES user_companies(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_order_responsible FOREIGN KEY (responsible_user_company_id) REFERENCES user_companies(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_order_kiosk FOREIGN KEY (source_kiosk_id) REFERENCES pos_restaurant_kiosks(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_order_register FOREIGN KEY (settlement_cash_register_id) REFERENCES pos_cash_registers(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_order_ticket FOREIGN KEY (ticket_id) REFERENCES pos_tickets(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_order_claimed_by FOREIGN KEY (claimed_by_user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_pos_restaurant_order_guests CHECK (guest_count BETWEEN 1 AND 1000),
    CONSTRAINT chk_pos_restaurant_order_status CHECK (status IN ('OPEN', 'IN_SERVICE', 'CHECK_REQUESTED', 'READY_FOR_CHECKOUT', 'CLAIMED_FOR_CHECKOUT', 'PAID', 'CLOSED', 'CANCELLED'))
);

CREATE TABLE pos_restaurant_order_items (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    kitchen_station_code VARCHAR(80) NOT NULL DEFAULT 'GENERAL',
    sku_snapshot VARCHAR(120) NULL,
    product_name_snapshot VARCHAR(240) NOT NULL,
    quantity DECIMAL(19,4) NOT NULL,
    unit_price DECIMAL(19,4) NOT NULL,
    line_total_amount DECIMAL(19,4) NOT NULL,
    notes VARCHAR(1000) NULL,
    modifier_summary VARCHAR(1000) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    sort_order INT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_pos_restaurant_item_order (company_id, order_id, status, sort_order),
    KEY idx_pos_restaurant_item_kitchen (company_id, kitchen_station_code, status, created_at),
    CONSTRAINT fk_pos_restaurant_item_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT fk_pos_restaurant_item_order FOREIGN KEY (order_id) REFERENCES pos_restaurant_orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pos_restaurant_item_product FOREIGN KEY (product_id) REFERENCES sales_products(id) ON DELETE RESTRICT,
    CONSTRAINT chk_pos_restaurant_item_values CHECK (quantity > 0 AND unit_price >= 0 AND line_total_amount >= 0),
    CONSTRAINT chk_pos_restaurant_item_status CHECK (status IN ('DRAFT', 'SENT', 'ACKNOWLEDGED', 'PREPARING', 'READY', 'SERVED', 'CANCELLED', 'VOIDED'))
);

